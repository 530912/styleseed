-- -----------------------------------------------------------------------------
-- storage.objects policies: first path folder must equal the caller's user id
-- -----------------------------------------------------------------------------
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and policyname = 'Users can read own clothing images'
  ) then
    create policy "Users can read own clothing images"
      on storage.objects
      as permissive
      for select
      to authenticated
      using (((bucket_id = 'clothing-images'::text) AND ((storage.foldername(name))[1] = ( SELECT (auth.uid())::text AS uid))));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and policyname = 'Users can upload own clothing images'
  ) then
    create policy "Users can upload own clothing images"
      on storage.objects
      as permissive
      for insert
      to authenticated
      with check (((bucket_id = 'clothing-images'::text) AND ((storage.foldername(name))[1] = ( SELECT (auth.uid())::text AS uid))));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and policyname = 'Users can update own clothing images'
  ) then
    create policy "Users can update own clothing images"
      on storage.objects
      as permissive
      for update
      to authenticated
      using (((bucket_id = 'clothing-images'::text) AND ((storage.foldername(name))[1] = ( SELECT (auth.uid())::text AS uid))))
      with check (((bucket_id = 'clothing-images'::text) AND ((storage.foldername(name))[1] = ( SELECT (auth.uid())::text AS uid))));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and policyname = 'Users can delete own clothing images'
  ) then
    create policy "Users can delete own clothing images"
      on storage.objects
      as permissive
      for delete
      to authenticated
      using (((bucket_id = 'clothing-images'::text) AND ((storage.foldername(name))[1] = ( SELECT (auth.uid())::text AS uid))));
  end if;
end
$$;
