-- -----------------------------------------------------------------------------
-- public.clothes
-- -----------------------------------------------------------------------------
create table if not exists public.clothes (
  id bigint generated by default as identity
    (start with 1 increment by 1 minvalue 1 no maxvalue cache 1 no cycle),
  user_id uuid not null,
  category text not null,
  sub_category text not null,
  color text not null,
  color_tone text not null,
  fit text not null,
  material text not null,
  season text[] not null default '{}'::text[],
  tpo text[] not null default '{}'::text[],
  style text[] not null default '{}'::text[],
  original_image_path text,
  created_at timestamp with time zone not null default now(),
  cutout_image_path text,
  constraint clothes_pkey primary key (id),
  constraint clothes_user_id_fkey foreign key (user_id)
    references auth.users (id) on delete cascade
);

alter table public.clothes enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'clothes'
      and policyname = 'Users can read own clothes'
  ) then
    create policy "Users can read own clothes"
      on public.clothes
      as permissive
      for select
      to authenticated
      using ((( SELECT auth.uid() AS uid) = user_id));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'clothes'
      and policyname = 'Users can insert own clothes'
  ) then
    create policy "Users can insert own clothes"
      on public.clothes
      as permissive
      for insert
      to authenticated
      with check ((( SELECT auth.uid() AS uid) = user_id));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'clothes'
      and policyname = 'Users can update own clothes'
  ) then
    create policy "Users can update own clothes"
      on public.clothes
      as permissive
      for update
      to authenticated
      using ((( SELECT auth.uid() AS uid) = user_id))
      with check ((( SELECT auth.uid() AS uid) = user_id));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'clothes'
      and policyname = 'Users can delete own clothes'
  ) then
    create policy "Users can delete own clothes"
      on public.clothes
      as permissive
      for delete
      to authenticated
      using ((( SELECT auth.uid() AS uid) = user_id));
  end if;
end
$$;

